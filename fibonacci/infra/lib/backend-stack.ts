import * as path from 'path';
import { Stack, StackProps, CfnOutput, Duration } from 'aws-cdk-lib';
import { Construct } from 'constructs';
import * as dynamodb from 'aws-cdk-lib/aws-dynamodb';
import * as ecrAssets from 'aws-cdk-lib/aws-ecr-assets';
import * as apprunner from '@aws-cdk/aws-apprunner-alpha';

export interface BackendStackProps extends StackProps {
  /** Amplify Hosting origin allowed to call the API. Defaults to the local dev origin. */
  readonly corsAllowedOrigin?: string;
}

export class BackendStack extends Stack {
  public readonly serviceUrl: string;

  constructor(scope: Construct, id: string, props: BackendStackProps) {
    super(scope, id, props);

    const table = dynamodb.Table.fromTableName(this, 'ChatsTable', 'FibonacciChats');

    const image = new ecrAssets.DockerImageAsset(this, 'ApiImage', {
      directory: path.join(__dirname, '../../backend/Api'),
      // App Runner requires x86_64 images; local builds on Apple Silicon default to arm64.
      platform: ecrAssets.Platform.LINUX_AMD64,
    });

    const service = new apprunner.Service(this, 'ApiService', {
      serviceName: 'fibonacci-api',
      cpu: apprunner.Cpu.QUARTER_VCPU,
      memory: apprunner.Memory.HALF_GB,
      source: apprunner.Source.fromAsset({
        asset: image,
        imageConfiguration: {
          port: 8080,
          environmentVariables: {
            Aws__Region: this.region,
            Aws__TableName: table.tableName,
            Cors__AllowedOrigin: props.corsAllowedOrigin ?? 'http://localhost:5173',
          },
        },
      }),
      healthCheck: apprunner.HealthCheck.http({
        path: '/health',
        interval: Duration.seconds(10),
        timeout: Duration.seconds(5),
        healthyThreshold: 2,
        unhealthyThreshold: 5,
      }),
    });

    // Instance role auto-generated by the Service construct, scoped to exactly this table.
    table.grantReadWriteData(service);

    this.serviceUrl = `https://${service.serviceUrl}`;
    new CfnOutput(this, 'ServiceUrl', { value: this.serviceUrl });
  }
}
